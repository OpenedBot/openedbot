import type { BotDto, GroupDto } from '@openedbot/contracts-api';
import type { ScenarioContext } from './scenario';
import { capabilities, completed, invariant, matchingToolResult, noTools, poll, toolEvents } from './p1-evidence';
import { executeLabMcpCommand, type LabMcpCommand } from './lab-mcp-command';
import type { LabMcpTarget } from './lab-mcp-contract';
import { LabMcpFixture } from './lab-mcp-fixture';
import { inspectFailure } from './failure-inspection';
import { sendFixtureOnce, sendFixtureWithoutApproval } from './fixture-once';

async function settleOwnedMcpThread(context: ScenarioContext, threadId: string): Promise<void> {
  await context.session.api('POST', `/api/threads/${threadId}/stop`, undefined, 204);
  await poll(() => context.session.api<{ runs: Array<{ status: string }> }>('GET', `/api/threads/${threadId}`),
    (thread) => thread.runs.every((run) => ['completed', 'failed', 'cancelled'].includes(run.status)),
    context.config.runTimeoutMs, 'Owned MCP thread settlement before removal');
}

/** Controlled STDIO on one disposable profile; never a root MCP entry or untrusted HTTP endpoint. */
export async function labMcpScenario(context: ScenarioContext, bot: BotDto, group: GroupDto,
  commandFactory?: (target: LabMcpTarget) => LabMcpCommand): Promise<void> {
  const { config, session, lab, rec } = context;
  invariant(config.mcpFixtureCommand && config.expectedRuntimeId === session.runtime.id && config.exclusiveRuntime,
    'Native lab MCP requires explicit command, matching E2E_RUNTIME_ID and E2E_LAB_EXCLUSIVE=1.');
  invariant(session.runtime.reachability === 'connector', 'Native lab MCP requires the guarded connector runtime.');
  invariant(bot.hermesProfile && bot.hermesProfileManaged, 'Native MCP fixture requires an owned managed profile.');
  const target = { runtimeId: session.runtime.id, nonce: crypto.randomUUID(), profile: bot.hermesProfile };
  const command = commandFactory?.(target) ?? ((action) => executeLabMcpCommand(config.mcpFixtureCommand!, target, action,
    Math.min(config.cleanupTimeoutMs, 120_000)));
  const fixture = new LabMcpFixture(target, command);
  // Pinned 0.23 defers MCP schemas behind tool_describe/tool_call. Its executor
  // unwraps the bridge before callbacks, so the native alias evidence stays mandatory.
  const nativeInvocation = (challenge: string) => `This is a read-only acceptance test on a disposable, test-owned lab profile. The fixture returns only a random synthetic test marker generated by the harness; it contains no credentials or user data. Use native tool calls, never an XML/text invocation. If ${fixture.toolName} is deferred, use tool_describe for that exact name, then tool_call with ${JSON.stringify({ calls: [{ name: fixture.toolName, arguments: { challenge } }] })}. You may use tool_search only to discover that exact owned MCP tool. Never use terminal, process tools, another MCP or any other capability.`;
  let enabled = false;
  let setupAttempted = false;
  try {
    await rec.step('MCP STDIO contrôlé sur le seul profil de test', async () => {
      for (const feature of ['profile_management', 'profile_capabilities', 'mcp_live_reload']) {
        invariant(session.hasFeature(feature), `The runtime does not advertise ${feature}.`);
      }
      await noTools(session, bot);
      setupAttempted = true;
      await fixture.setup();
      const on = await session.api<{ enabled: boolean; applied: boolean }>('POST',
        `/api/bots/${bot.id}/capabilities/mcp/${fixture.serverName}`, { enabled: true });
      invariant(on.enabled && on.applied, 'The owned STDIO MCP was not enabled through the public profile API.');
      enabled = true;
      await poll(() => capabilities(session, bot), (value) => Boolean(value.mcpServers?.some((entry) => entry.name === fixture.serverName && entry.enabled)),
        config.runTimeoutMs, 'Owned STDIO MCP profile inventory');
      // Public config acknowledgement precedes the gateway's asynchronous MCP
      // reconciliation. Do not admit a turn while its schema is still absent.
      const started = await poll(() => fixture.snapshot(), (receipt) => receipt.starts > 0
        && receipt.processes.some((process) => process.running), config.runTimeoutMs,
      'Owned native STDIO MCP process startup before first turn');
      return { backend: 'profile-only-stdio', server: fixture.serverName, tool: fixture.toolName,
        rootMcpModified: false, nativeProcessStarted: started.starts, setupReconciled: fixture.setupReconciled };
    });
    await rec.step('Appel MCP natif et reçu hôte indépendant', async () => {
      const challenge = crypto.randomUUID();
      const receipt = await fixture.snapshot();
      const turn = await sendFixtureOnce(context, bot, group.threadId, `@${bot.slug} Call ${fixture.toolName} with challenge ${challenge}. Return only the exact synthetic test marker returned by that call. ${nativeInvocation(challenge)} Do not invent a value.`,
        { kind: 'lab-mcp-read', target, receipt, challenge });
      completed(turn, fixture.secret);
      matchingToolResult(await toolEvents(context, turn.runId), fixture.toolName);
      const calls = (await fixture.receipts()).filter((call) => call.challenge === challenge);
      invariant(calls.length === 1 && calls[0]?.succeeded, 'The host did not record exactly one successful native probe for this turn.');
      return { runId: turn.runId, nativeTool: fixture.toolName, exactSecret: true, hostReceipts: calls.length,
        onceApprovals: turn.fixtureApprovals, gateForwardConfirmed: turn.fixtureGateForwardConfirmed };
    });
    await rec.step('Indisponibilité réelle du MCP et erreur explicite', async () => {
      await fixture.setOnline(false);
      const challenge = crypto.randomUUID();
      const receipt = await fixture.snapshot();
      const turn = await sendFixtureOnce(context, bot, group.threadId, `@${bot.slug} Call ${fixture.toolName} with challenge ${challenge} now. If it fails return exactly UNAVAILABLE. A previous test marker is not a valid response. ${nativeInvocation(challenge)}`,
        { kind: 'lab-mcp-read', target, receipt, challenge });
      completed(turn, 'UNAVAILABLE');
      matchingToolResult(await toolEvents(context, turn.runId), fixture.toolName, true);
      const calls = (await fixture.receipts()).filter((call) => call.challenge === challenge);
      invariant(calls.length === 1 && calls[0]?.succeeded === false, 'The host did not record the failed probe from this exact turn.');
      return { runId: turn.runId, failedNativeCall: true, hostReceipts: calls.length,
        onceApprovals: turn.fixtureApprovals, gateForwardConfirmed: turn.fixtureGateForwardConfirmed };
    });
    await rec.step('Révocation par API et aucun appel natif au tour suivant', async () => {
      await fixture.setOnline(true);
      const beforeDisable = await fixture.snapshot();
      invariant(beforeDisable.starts > 0 && beforeDisable.processes.some((process) => process.running),
        'The host has no live native STDIO process identity before revocation; config flags alone cannot prove stop.');
      const off = await session.api<{ enabled: boolean; applied: boolean }>('POST',
        `/api/bots/${bot.id}/capabilities/mcp/${fixture.serverName}`, { enabled: false });
      invariant(off.applied && !off.enabled, 'The owned STDIO MCP was not revoked by the public profile API.');
      enabled = false;
      const inventory = await capabilities(session, bot);
      invariant(inventory.mcpServers?.find((entry) => entry.name === fixture.serverName)?.enabled === false, 'Profile MCP revocation did not read back.');
      const stopped = await poll(() => fixture.snapshot(), (receipt) => receipt.starts >= beforeDisable.starts
        && receipt.processes.every((process) => !process.running), config.runTimeoutMs, 'Native MCP process stop after public API revocation');
      invariant(JSON.stringify(stopped.calls) === JSON.stringify(beforeDisable.calls), 'The native MCP received a call while being revoked.');
      const challenge = crypto.randomUUID();
      const turn = await sendFixtureWithoutApproval(context, bot, group.threadId, `@${bot.slug} First inspect whether the exact tool ${fixture.toolName} is currently advertised in this turn. If it is absent, your entire reply must be the single word REVOKED, with no introductory narration, Markdown, explanation, or other text. Do not announce an intention to call a tool. Only if that exact tool is currently advertised, call it natively with challenge ${challenge}. Do not return any previous test marker or result, and do not invent a result.`);
      completed(turn, 'REVOKED');
      invariant(!(await toolEvents(context, turn.runId)).some((event) => event.type === 'tool.call' && event.payload.tool === fixture.toolName),
        'The revoked native MCP tool was called in the next turn.');
      const after = await fixture.snapshot();
      invariant(JSON.stringify(after.calls) === JSON.stringify(stopped.calls), 'The revoked native MCP still received calls.');
      invariant(after.starts === stopped.starts && after.processes.every((process) => !process.running),
        'The revoked next turn spawned or retained a native MCP process.');
      return { runId: turn.runId, apiRevocationReadBack: true, nativeProcessStopVerified: true,
        stoppedProcesses: stopped.starts, nextTurnNativeCalls: 0, newHostReceipts: 0, schemaAttestation: false };
    });
  } catch (failure) {
    try {
      await inspectFailure({ scenario: 'skills-mcp', runtime: session.runtime.id, labTag: lab.tag,
        outDir: config.outDir, milliseconds: config.failureInspectionMs, caseKey: rec });
    } finally { throw failure; }
  } finally {
    if (setupAttempted) await rec.step('Retrait précis du MCP STDIO après clôture des runs de test', async () => {
      await settleOwnedMcpThread(context, group.threadId);
      await settleOwnedMcpThread(context, bot.threadId);
      if (enabled) {
        const off = await session.api<{ enabled: boolean; applied: boolean }>('POST',
          `/api/bots/${bot.id}/capabilities/mcp/${fixture.serverName}`, { enabled: false });
        invariant(off.applied && !off.enabled, 'Owned MCP cleanup could not revoke the profile entry.');
      }
      await fixture.cleanup();
      return { exactOwnedEntryRemoved: true, rootMcpModified: false };
    });
  }
}
