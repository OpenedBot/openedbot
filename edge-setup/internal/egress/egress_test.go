func addrs(t *testing.T, in ...string) []netip.Addr {
	t.Helper()
	var out []netip.Addr
	for _, s := range in {
		out = append(out, netip.MustParseAddr(s))
	}
	return out
}

// deniedRange skips a range that does not parse, so a typo in the list would
// silently turn the exception off: the list itself is under test.
func TestDeniedRangesAreWellFormed(t *testing.T) {
	for _, network := range layout.EgressDenyNetworks {
		if _, err := netip.ParsePrefix(network); err != nil {
			t.Errorf("layout.EgressDenyNetworks %q: %v", network, err)
		}
	}
	for addr, want := range map[string]bool{
		"169.254.169.254": true, "169.254.170.2": true, "fd00:ec2::254": true, "fd00:ec2::253": true,
		"127.0.0.53": false, "127.0.0.1": false, "::1": false, "1.1.1.1": false, "fe80::1": false, "fd00:ec3::1": false,
	} {
		if got := Denied(netip.MustParseAddr(addr)); got != want {
			t.Errorf("Denied(%s) = %v, want %v", addr, got, want)
		}
	}
}

func TestNameserversReadsTheLinesAResolverWould(t *testing.T) {
	resolvConf := "# Generated by NetworkManager\r\n" +
		"search c.example.internal google.internal\n" +
		"nameserver 169.254.169.254\n" +
		"\tnameserver  fe80::1%eth0\n" +
		"nameserver fd00:ec2::253\n" +
		";nameserver 10.0.0.1\n" +
		"# nameserver 10.0.0.2\n" +
		"nameserver not-an-address\n" +
		"nameserver ::ffff:169.254.169.253\n" +
		"nameserver 127.0.0.53 # the stub\n" +
		"nameserver\n" +
		"options edns0 trust-ad\n"
	want := addrs(t, "169.254.169.254", "fe80::1", "fd00:ec2::253", "169.254.169.253", "127.0.0.53")
	if got := Nameservers(resolvConf); !slices.Equal(got, want) {
		t.Errorf("Nameservers = %v, want %v", got, want)
	}
	if got := Nameservers(""); len(got) != 0 {
		t.Errorf("an empty resolv.conf names no resolver, got %v", got)
	}
}

// Only a resolver inside a denied range needs the exception; the stub of
// systemd-resolved, an ordinary resolver and a link-local IPv6 one do not.
func TestResolverAllowKeepsOnlyResolversInsideADeniedRange(t *testing.T) {
	got := ResolverAllow(addrs(t,
		"169.254.169.254", "fe80::1", "fd00:ec2::253", "169.254.169.254", "127.0.0.53", "1.1.1.1", "2001:4860:4860::8888"))
	want := addrs(t, "169.254.169.254", "fd00:ec2::253")
	if !slices.Equal(got, want) {
		t.Errorf("ResolverAllow = %v, want %v", got, want)
	}
	if got := ResolverAllow(addrs(t, "127.0.0.53")); len(got) != 0 {
		t.Errorf("the systemd-resolved stub needs no exception, got %v", got)
	}
}

func TestResolverAllowFromReadsTheFileAndLogsEachException(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	if err := os.WriteFile(path, []byte("nameserver 169.254.169.254\nnameserver 127.0.0.53\nnameserver fd00:ec2::253\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	var logged []string
	log := func(format string, args ...any) { logged = append(logged, fmt.Sprintf(format, args...)) }
	got := ResolverAllowFrom(path, "the gateway unit", log)
	if want := addrs(t, "169.254.169.254", "fd00:ec2::253"); !slices.Equal(got, want) {
		t.Errorf("ResolverAllowFrom = %v, want %v", got, want)
	}
	if len(logged) != 2 {
		t.Fatalf("one log line per exception, got %q", logged)
	}
	for i, want := range []string{
		"the gateway unit: nameserver 169.254.169.254 is inside 169.254.0.0/16",
		"the gateway unit: nameserver fd00:ec2::253 is inside fd00:ec2::/64",
	} {
		if !strings.HasPrefix(logged[i], want) || !strings.Contains(logged[i], "IPAddressAllow="+got[i].String()+"/") {
			t.Errorf("log line %d = %q, want it to start with %q and name its IPAddressAllow=", i, logged[i], want)
		}
	}

	// No exception, no line: a stub resolver is the common case.
	if err := os.WriteFile(path, []byte("nameserver 127.0.0.53\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	logged = nil
	if got := ResolverAllowFrom(path, "the gateway unit", log); len(got) != 0 || len(logged) != 0 {
		t.Errorf("a stub resolver must yield no exception and no log, got %v %q", got, logged)
	}
}

func TestResolverAllowFromWithoutAReadableResolvConf(t *testing.T) {
	var logged []string
	log := func(format string, args ...any) { logged = append(logged, fmt.Sprintf(format, args...)) }
	dir := t.TempDir()
	if got := ResolverAllowFrom(filepath.Join(dir, "absent"), "the units", log); len(got) != 0 || len(logged) != 0 {
		t.Errorf("a missing resolv.conf names no resolver and is not worth a line, got %v %q", got, logged)
	}
	// A directory is not a resolv.conf: no exception, and the operator hears of it.
	if got := ResolverAllowFrom(dir, "the units", log); len(got) != 0 || len(logged) != 1 || !strings.Contains(logged[0], "cannot read") {
		t.Errorf("an unreadable resolv.conf must yield no exception and one line, got %v %q", got, logged)
	}
	if got := ResolverAllowFrom(filepath.Join(dir, "absent"), "the units", nil); len(got) != 0 {
		t.Errorf("a nil log must be accepted, got %v", got)
	}
}

// UFW filters the whole host: the upstreams behind the systemd-resolved stub
// count there, and the daemon's own file lists them.
func TestResolverAllowFromFilesReadsEveryFileOnce(t *testing.T) {
	dir := t.TempDir()
	etc := filepath.Join(dir, "resolv.conf")
	upstream := filepath.Join(dir, "resolved.conf")
	if err := os.WriteFile(etc, []byte("nameserver 127.0.0.53\noptions edns0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(upstream, []byte("nameserver 169.254.169.254\nnameserver 1.1.1.1\nnameserver fd00:ec2::253\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	got, err := ResolverAllowFromFiles([]string{etc, upstream})
	if err != nil {
		t.Fatal(err)
	}
	if want := addrs(t, "169.254.169.254", "fd00:ec2::253"); !slices.Equal(got, want) {
		t.Errorf("ResolverAllowFromFiles = %v, want %v", got, want)
	}

	// The same resolver named by both files is one exception, in file order.
	if err := os.WriteFile(etc, []byte("nameserver fd00:ec2::253\nnameserver 169.254.169.254\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	got, err = ResolverAllowFromFiles([]string{etc, upstream})
	if err != nil {
		t.Fatal(err)
	}
	if want := addrs(t, "fd00:ec2::253", "169.254.169.254"); !slices.Equal(got, want) {
		t.Errorf("ResolverAllowFromFiles = %v, want %v", got, want)
	}
}

func TestResolverAllowFromFilesSkipsAMissingFileAndFailsOnAnUnreadableOne(t *testing.T) {
	dir := t.TempDir()
	etc := filepath.Join(dir, "resolv.conf")
	if err := os.WriteFile(etc, []byte("nameserver 169.254.169.254\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	// Without systemd-resolved its file is absent, and the other still counts.
	got, err := ResolverAllowFromFiles([]string{etc, filepath.Join(dir, "absent")})
	if err != nil || !slices.Equal(got, addrs(t, "169.254.169.254")) {
		t.Errorf("a missing file must be skipped, got %v, %v", got, err)
	}
	if got, err := ResolverAllowFromFiles(nil); err != nil || len(got) != 0 {
		t.Errorf("no file names no resolver, got %v, %v", got, err)
	}
	// A directory is not a resolv.conf: the firewall cannot prove where the
	// host's resolver lies, so the call fails and names the file.
	if _, err := ResolverAllowFromFiles([]string{etc, dir}); err == nil || !strings.Contains(err.Error(), dir) {
		t.Errorf("an unreadable file must fail naming it, got %v", err)
	}
}

func TestWithinKeepsTheAddressesOfOneRange(t *testing.T) {
	all := addrs(t, "169.254.169.254", "fd00:ec2::253", "127.0.0.53", "169.254.169.253")
	if got, want := Within(all, "169.254.0.0/16"), addrs(t, "169.254.169.254", "169.254.169.253"); !slices.Equal(got, want) {
		t.Errorf("Within(169.254.0.0/16) = %v, want %v", got, want)
	}
	if got, want := Within(all, "fd00:ec2::/64"), addrs(t, "fd00:ec2::253"); !slices.Equal(got, want) {
		t.Errorf("Within(fd00:ec2::/64) = %v, want %v", got, want)
	}
	if got := Within(all, "not-a-network"); len(got) != 0 {
		t.Errorf("an unparsable network holds nothing, got %v", got)
	}
}
